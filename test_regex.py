#!/usr/bin/env python3
import re

# 测试用的正则表达式（修正后的版本）
phase_patterns = {
    51: r'obs_\[51\] = phase\[0\] = ([+-]?[0-9]*\.?[0-9]+([eE][+-]?[0-9]+)?)',
    52: r'obs_\[52\] = phase\[1\] = ([+-]?[0-9]*\.?[0-9]+([eE][+-]?[0-9]+)?)',
    53: r'obs_\[53\] = phase\[2\] = ([+-]?[0-9]*\.?[0-9]+([eE][+-]?[0-9]+)?)',
    54: r'obs_\[54\] = phase\[3\] = ([+-]?[0-9]*\.?[0-9]+([eE][+-]?[0-9]+)?)',
    55: r'obs_\[55\] = phase\[4\] = ([+-]?[0-9]*\.?[0-9]+([eE][+-]?[0-9]+)?)',
    56: r'obs_\[56\] = phase\[5\] = ([+-]?[0-9]*\.?[0-9]+([eE][+-]?[0-9]+)?)'
}

# 测试数据
test_lines = [
    '[2026-02-10 16:33:40.456] obs_[51] = phase[0] = 2.11434e-06',
    '[2026-02-10 16:33:40.456] obs_[52] = phase[1] = 0.999998',
    '[2026-02-10 16:33:40.456] obs_[53] = phase[2] = 1.46361e-11',
    '[2026-02-10 16:33:40.456] obs_[54] = phase[3] = 1',
    '[2026-02-10 16:33:40.456] obs_[55] = phase[4] = 0',
    '[2026-02-10 16:33:40.456] obs_[56] = phase[5] = 6.24611e-13'
]

print("测试正则表达式匹配科学计数法:")
print("=" * 50)

for i, line in enumerate(test_lines, 51):
    pattern = phase_patterns[i]
    match = re.search(pattern, line)
    if match:
        value = match.group(1)
        print(f"✓ obs_[{i}] 匹配成功: {value}")
    else:
        print(f"✗ obs_[{i}] 匹配失败")

print("\n" + "=" * 50)
print("测试完成!")